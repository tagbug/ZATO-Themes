"""Build the Shell styles and release archives."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
THEMES = ("ZATO-Night", "ZATO-Dawn")
UUID = "zato-on-the-line@tagbug.github.io"


def shell_css(folder):
    palette = json.loads((folder / "palette.json").read_text())
    css = (ROOT / "vendor/gnome-shell-50/gnome-shell-dark.css").read_text()
    css = re.sub(r"#[0-9a-fA-F]{6}",
                 lambda match: palette["shellMap"].get(match.group().lower(), match.group()), css)
    css = css.replace("-st-accent-fg-color", palette["colors"]["accentFg"])
    css = css.replace("-st-accent-color", palette["colors"]["accent"])
    if palette["warmOverlay"]:
        css = re.sub(r"rgba\(255,\s*255,\s*255,", "rgba(233,223,208,", css)
    version = (ROOT / "VERSION").read_text().strip()
    return (f"/* {palette['name']} {version}. Generated by tools/build.py. */\n"
            + css + "\n" + (folder / "gnome-shell/zato-overrides.css").read_text())


def archive(path, files):
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as output:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            output.writestr(info, data)
    with zipfile.ZipFile(path) as output:
        if output.testzip() is not None:
            raise RuntimeError(f"Invalid archive: {path}")


def release():
    version = (ROOT / "VERSION").read_text().strip()
    destination = ROOT / "dist"
    destination.mkdir(exist_ok=True)
    packages = []
    for name in THEMES:
        folder = ROOT / "themes" / name
        files = {str(file.relative_to(folder.parent)): file.read_bytes()
                 for file in folder.rglob("*") if file.is_file()}
        for source, target in [("LICENSE", "LICENSE"), ("THIRD_PARTY.md", "THIRD_PARTY.md"),
                               ("vendor/gnome-shell-50/COPYING.LIB", "COPYING.LIB")]:
            files[f"{name}/{target}"] = (ROOT / source).read_bytes()
        package = destination / f"{name}-{version}.zip"
        archive(package, files)
        packages.append(package)
    widget = ROOT / "widget" / UUID
    files = {str(file.relative_to(widget)): file.read_bytes()
             for file in widget.rglob("*") if file.is_file() and file.name != "gschemas.compiled"}
    with tempfile.TemporaryDirectory(prefix="zato-schemas-") as temporary:
        subprocess.run(["glib-compile-schemas", "--strict", "--targetdir", temporary,
                        str(widget / "schemas")], check=True)
        files["schemas/gschemas.compiled"] = (Path(temporary) / "gschemas.compiled").read_bytes()
    files["README.md"] = (ROOT / "docs/WIDGET.md").read_bytes()
    package = destination / f"ZATO-On-the-Line-{version}.shell-extension.zip"
    archive(package, files)
    packages.append(package)
    source = {}
    for file in ROOT.rglob("*"):
        relative = file.relative_to(ROOT)
        if not file.is_file() or any(part in {"dist", ".git", "__pycache__"} for part in relative.parts):
            continue
        if file.name == "gschemas.compiled":
            continue
        source[f"ZATO-Themes-{version}/{relative}"] = file.read_bytes()
    package = destination / f"ZATO-Themes-{version}.zip"
    archive(package, source)
    packages.append(package)
    sums = "".join(hashlib.sha256(file.read_bytes()).hexdigest() + "  " + file.name + "\n"
                   for file in packages)
    (destination / "SHA256SUMS").write_text(sums)
    for file in packages:
        print(file.relative_to(ROOT))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated CSS without writing it")
    parser.add_argument("--release", action="store_true", help="build archives under dist/")
    args = parser.parse_args()
    for name in THEMES:
        folder = ROOT / "themes" / name
        output = folder / "gnome-shell/gnome-shell.css"
        expected = shell_css(folder)
        if args.check:
            if output.read_text() != expected:
                raise SystemExit(f"Outdated CSS: {output.relative_to(ROOT)}")
        else:
            output.write_text(expected)
    subprocess.run(["glib-compile-schemas", "--strict", "--dry-run",
                    str(ROOT / "widget" / UUID / "schemas")], check=True)
    if args.release:
        release()
    elif args.check:
        print("Shell CSS and widget schemas checked.")


if __name__ == "__main__":
    main()
